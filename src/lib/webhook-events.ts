/**
 * Webhookイベントの二重処理を防ぐ（idempotency）
 *
 * ─────────────────────────────────────────────
 * なぜ必要か
 * ─────────────────────────────────────────────
 * Stripeは、こちらが200を返せなかったときに同じイベントを再送する。
 * また、まれに同じイベントが複数回届くこともある。
 * そのまま処理すると、注文メールが二重に飛ぶ、在庫を二重に引くといった
 * 事故につながるため、一度処理したイベントIDは無視する。
 *
 * ─────────────────────────────────────────────
 * いまの実装と、その限界
 * ─────────────────────────────────────────────
 * 注文を保存するデータベースがまだないため、
 * サーバーのメモリ上にイベントIDを覚えている。
 *
 * Vercelでは処理ごとにインスタンスが分かれたり、
 * しばらく使われないと停止したりするため、この記憶は永続しない。
 * つまり「同じ処理内での再送」は防げるが、完全ではない。
 *
 * ★ 注文をデータベースに保存する、または注文メールを送るようになったら、
 *   その保存先で「このイベントIDはもう処理したか」を判定するように
 *   置き換えること。そのときはこのファイルは不要になる。
 */

/** 覚えておくイベントIDの上限（メモリを使いすぎないため） */
const MAX_ENTRIES = 500;

const processed = new Set<string>();

/**
 * このイベントを処理してよいか。
 * 初めてなら true を返し、同時にIDを記録する。
 * すでに処理済みなら false。
 */
export function markEventProcessed(eventId: string): boolean {
  if (processed.has(eventId)) return false;

  // 上限を超えたら、古いものから捨てる（Setは挿入順を保つ）
  if (processed.size >= MAX_ENTRIES) {
    const oldest = processed.values().next().value;
    if (oldest) processed.delete(oldest);
  }

  processed.add(eventId);
  return true;
}
